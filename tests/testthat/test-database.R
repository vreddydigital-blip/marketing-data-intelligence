test_that("SQLite schema initialises and CRUD works with parameterised queries", {
  old <- Sys.getenv("MDI_DATA_DIR")
  Sys.setenv(MDI_DATA_DIR = tempfile())
  on.exit({ Sys.setenv(MDI_DATA_DIR = old); unlink(temp_d(), recursive = TRUE) }, add = TRUE)
  temp_d <- function() Sys.getenv("MDI_DATA_DIR")
  expect_no_error(mdi_db_init())
  id <- mdi_db_add_dataset("t1", "Test 1", 10, 3, 1000, is_sample = TRUE,
                           metadata = list(quality = "90"))
  expect_type(id, "integer")
  mdi_db_log_cleaning_op(id, "dedupe", "removed 2")
  mdi_db_log_analysis(id, "eda", "checked summary")
  mdi_db_setting_set("k", "v1")
  expect_equal(mdi_db_setting_get("k"), "v1")
  mdi_db_setting_set("k", "v2")
  expect_equal(mdi_db_setting_get("k"), "v2")
  h <- mdi_db_list_history()
  expect_true(nrow(h) >= 1)
  expect_true("Test 1" %in% h$dataset | all(h$dataset == "-"))
})
